"""Render the per-repo .devflow/config.toml and the prompt files from a detected Profile."""

from __future__ import annotations

import json
from pathlib import Path
from string import Template

from .detect import GATES, Profile
from .graphify import GraphResult

TEMPLATE_DIR = Path(__file__).parent / "templates"
SCHEMA_DIR = Path(__file__).parent / "schemas"
PROMPTS = ("planner", "test_planner", "coder", "reviewer", "triage", "retro")
SCHEMAS = ("plan", "test_plan", "review", "triage", "lesson")


def _s(value: str) -> str:
    return json.dumps(value)


def _list(values: list[str]) -> str:
    return "[" + ", ".join(_s(v) for v in values) + "]"


CODING_AGENTS = ("claude", "codex", "cursor")


def pick_agents(available: list[str]) -> tuple[str, str, list[str]]:
    """Default coder and reviewer. They should be different tools when more than one exists."""
    ordered = [a for a in CODING_AGENTS if a in available]
    if not ordered:
        missing = (
            "no coding agent (`claude`, `codex` or `agent`) found on PATH: "
            "install one before running tickets"
        )
        return "claude", "claude", [missing]
    coder = ordered[0]
    if len(ordered) > 1:
        return coder, ordered[1], []
    same = (
        "only one coding agent installed: the reviewer will be the same model as the coder, "
        "so reviews are less independent"
    )
    return coder, coder, [same]


def render_routing(available: list[str]) -> list[str]:
    """Default routing: spread coding-heavy work across whatever agents are installed."""
    lines = [
        "",
        "# Coding-heavy roles are routed across the agents below by remaining headroom in",
        "# their budget window. limit_usd = 0 means no local cap (rate-limit errors still",
        "# trigger a cooldown). Set limit_usd to your own comfort level per window.",
        "[routing]",
        'roles = ["coder", "reviewer", "test_planner"]',
        'strategy = "headroom"   # or "priority": always prefer the lowest priority number',
        "cooldown_minutes = 30",
        "cooldown_max_hours = 6",
    ]
    for rank, name in enumerate([a for a in CODING_AGENTS if a in available], start=1):
        lines += ["", f"[routing.agents.{name}]", f"priority = {rank}", "window_hours = 5",
                  "limit_usd = 0"]
    return lines


def needs_input(profile: Profile, agent_warnings: list[str]) -> list[str]:
    items = list(agent_warnings)
    if not profile.projects:
        items.append("no build/test project detected: define gates in .devflow/config.toml")
    for p in profile.projects:
        if "unit" not in p.gates:
            items.append(f"project {p.path!r}: no unit-test command detected")
        elif "integration" not in p.gates:
            items.append(
                f"project {p.path!r}: no integration-test command detected; the review stage "
                "needs one to verify changes end to end"
            )
    if profile.ci_hints and not any(p.gates for p in profile.projects):
        items.append("CI runs commands the detector could not map to gates; see [ci] hints")
    return items


def render_config(
    profile: Profile, coder: str, reviewer: str, graph: GraphResult | None,
    available: list[str] | None = None,
) -> str:
    lines = [
        f"# devflow config for {profile.name}.",
        "# Generated by `devflow init` from what was detected in the repo. Edit freely;",
        "# re-running init never overwrites this file unless you pass --force.",
        "",
        "[repo]",
        f"name = {_s(profile.name)}",
        f"default_branch = {_s(profile.default_branch or 'main')}",
        f"remote = {_s(profile.remote or '')}",
        f"worktree_root = {_s('~/.devflow/worktrees/' + profile.name)}",
        "",
        "[limits]",
        "max_review_rounds = 3",
        "max_implement_attempts = 3",
        "stage_timeout_minutes = 45",
        "gate_timeout_minutes = 20",
        "",
        "[human_gates]",
        "plan_approval = true",
        "merge_approval = true",
        "# GitHub logins allowed to /approve, /answer, /reject and /resume (default: the gh user)",
        "# approvers = []",
        "# Run when a ticket needs you; {text} is the message. Example (iMessage via imsg):",
        '# notify_command = "imsg send --to +15551234567 --text {text}"',
        "",
        "# Review is still allowed when a repo has no integration gate (the PR notes the gap).",
        "# Set true to refuse to review, and escalate, until an integration gate exists.",
        "[review]",
        "require_integration = false",
        "",
        "# Lessons learned from finished tickets. They start as candidates and reach prompts only",
        "# after recurring in `promote_after` tickets, or when a person states them (/learn).",
        "[learning]",
        "enabled = true",
        "budget_chars = 4000",
        "promote_after = 2",
        "max_idle_runs = 40",
        "",
        "# The GitHub Project that holds the queue (needs `gh auth refresh -s project`).",
        "# Statuses it must have: Backlog, Ready, In progress, In review, Done.",
        "# [github]",
        "# project = 3              # the Project's number; 0 or absent = no board",
        '# owner = "your-login"     # user or org that owns the Project',
        '# label = "devflow"        # only issues with this label are worked',
        "# followups_per_ticket = 3 # cap on tickets filed from one ticket's findings",
        "# max_active = 1           # tickets worked at once",
        "",
        "[agents]",
        f"coder = {_s(coder)}",
        f"reviewer = {_s(reviewer)}",
        'planner = "openclaw:devflow"   # created by `devflow setup-openclaw`',
        'triage = "openclaw:devflow"',
        'retro = "openclaw:devflow"     # distils lessons after each ticket',
        "",
        "[graphify]",
        f"enabled = {'true' if graph and graph.ok else 'false'}",
    ]
    if graph and graph.ok:
        lines += [f"nodes = {graph.nodes}", f"edges = {graph.edges}"]
    lines += render_routing(available if available is not None else [coder, reviewer])
    lines += ["", "[ci]", f"workflows = {_list(profile.ci_workflows)}",
              f"hints = {_list(profile.ci_hints)}"]
    for p in profile.projects:
        lines += ["", "[[project]]", f"path = {_s(p.path)}", f"kind = {_s(p.kind)}"]
        if p.setup:
            lines.append(f"setup = {_list(p.setup)}")
        lines.append("[project.gates]")
        for gate in GATES:
            if gate in p.gates:
                lines.append(f"{gate} = {_list(p.gates[gate])}")
            else:
                lines.append(f"# {gate} = []  # not detected")
    return "\n".join(lines) + "\n"


def _gates_summary(profile: Profile) -> str:
    out = []
    for p in profile.projects:
        gates = "; ".join(f"{g}: {' && '.join(p.gates[g])}" for g in GATES if g in p.gates)
        out.append(f"- {p.path} ({p.kind}): {gates or 'no gates detected'}")
    return "\n".join(out) or "- no projects detected"


def render_prompt(name: str, profile: Profile, graph: GraphResult | None) -> str:
    text = (TEMPLATE_DIR / f"{name}.md").read_text()
    conventions = "\n".join(f"- {c}" for c in profile.conventions) or "- none found"
    return Template(text).safe_substitute(
        repo_name=profile.name,
        default_branch=profile.default_branch or "main",
        gates_summary=_gates_summary(profile),
        conventions=conventions,
        graph_summary=graph.summary() if graph else "Code graph: not built.",
    )


def read_schema(name: str) -> str:
    return (SCHEMA_DIR / f"{name}.schema.json").read_text()
